#!/usr/bin/env python3
"""Generate Locales/enUS.lua from the L["..."] strings used in the addon's Lua files.

The English text is the key (AceLocale: `L["text"] = true`), so the code reads naturally and a
missing translation falls back to English. Other locales go in Locales/<locale>.lua as
`L["English text"] = "translation"`.

Usage: scripts/gen-locale.py          # rewrite Locales/enUS.lua
       scripts/gen-locale.py --check  # exit 1 if enUS.lua is out of date (used in CI)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ["Core", "Compat", "Situations", "Options"]
OUT = ROOT / "Locales" / "enUS.lua"
KEY = re.compile(r'L\["((?:[^"\\\n]|\\.)*)"\]')

HEADER = """-- English (default) strings. GENERATED by scripts/gen-locale.py from the L["..."] uses in the
-- code; don't edit by hand. Translations go in Locales/<locale>.lua.
local ADDON_NAME, ns = ...

local L = LibStub("AceLocale-3.0"):NewLocale(ADDON_NAME, "enUS", true, true)
if L then
"""
FOOTER = """end

ns.L = LibStub("AceLocale-3.0"):GetLocale(ADDON_NAME)
"""


def collect():
    keys = []
    seen = set()
    for folder in SOURCES:
        for path in sorted((ROOT / folder).rglob("*.lua")):
            for key in KEY.findall(path.read_text()):
                if key not in seen:
                    seen.add(key)
                    keys.append(key)
    return keys


def render(keys):
    body = "".join(f'\tL["{k}"] = true\n' for k in keys)
    return HEADER + body + FOOTER


def main():
    text = render(collect())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("Locales/enUS.lua is out of date: run scripts/gen-locale.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(collect())} strings)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
